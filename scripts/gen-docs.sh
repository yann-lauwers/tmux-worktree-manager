#!/bin/bash
# scripts/gen-docs.sh - Generate COMMANDS.md from the doc-comment convention.
#
# Every function carries a doc-comment block directly above its definition; the
# FIRST line of that block is its one-line purpose. This assembles those purposes
# into COMMANDS.md — a Commands section (parsed from wt.sh's dispatch) plus a
# per-file function index — so the index regenerates from source and never drifts.
#
# Doc-comment convention (directly above each `fn_name() {`):
#   # <one-line imperative purpose>            <- required; the index entry
#   # Args: $1 x, $2 y                          <- optional
#   # Out:  stdout: ...                         <- optional (stdout return value)
#   # Side: writes X; sets GLOBAL; dies on Y    <- optional (side effects)
#
# The function index lists the PUBLIC surface only: private helpers (`_name`) and
# help emitters (`show_*_help`) are documented in-source but omitted here.
#
# Usage:
#   gen-docs.sh            # print COMMANDS.md to stdout
#   gen-docs.sh --write    # write COMMANDS.md in the repo root
#   gen-docs.sh --check    # regenerate and diff against the committed COMMANDS.md
#                          # (exit 1 on drift — the never-drift gate)
set -euo pipefail

WT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_FILE="$WT_ROOT/COMMANDS.md"

# purpose_of <file> <fn_name> — print a function's one-line purpose (first line of
# its doc-comment block), or empty if it has none.
purpose_of() {
    awk -v want="$2" '
        /^[[:space:]]*#/ { if (!in_block) { first=$0; in_block=1 } next }
        /^[a-zA-Z_][a-zA-Z0-9_]*\(\)[[:space:]]*\{/ {
            name=$0; sub(/\(\).*/, "", name)
            if (name == want && in_block) { p=first; sub(/^[[:space:]]*#[[:space:]]?/, "", p); print p; exit }
            in_block=0; next
        }
        { in_block=0 }
    ' "$1"
}

# emit_commands — parse wt.sh's dispatch case into a `wt <aliases>` -> purpose table
emit_commands() {
    printf '## Commands\n\n'
    printf 'The command surface, from `wt.sh`'"'"'s dispatch. Run `wt <command> --help` for full usage.\n\n'
    printf '| Command | Purpose |\n|---|---|\n'
    # Extract (case-label, handler) pairs from main()'s dispatch block.
    awk '
        /case "\$command" in/ { in_case=1; next }
        in_case && /^[[:space:]]*esac/ { in_case=0 }
        in_case && /^[[:space:]]*[a-z]/ && /\)$/ {
            label=$0; gsub(/[[:space:]]|\)/, "", label); pending=label; next
        }
        in_case && pending != "" && /cmd_[a-z_]+/ {
            match($0, /cmd_[a-z_]+/); handler=substr($0, RSTART, RLENGTH)
            print pending "\t" handler; pending=""
        }
    ' "$WT_ROOT/wt.sh" | while IFS=$'\t' read -r label handler; do
        # handler lives in commands/<name>.sh; find it and read its purpose
        local purpose="" f
        for f in "$WT_ROOT"/commands/*.sh; do
            if grep -qE "^${handler}\(\)" "$f"; then purpose=$(purpose_of "$f" "$handler"); break; fi
        done
        local cmd_disp="${label//|/, }"
        printf '| `wt %s` | %s |\n' "$cmd_disp" "${purpose:-—}"
    done
    printf '\n'
}

# emit_file_section <path> — Markdown table of public fn -> purpose for one file
emit_file_section() {
    local file="$1"
    local rel="${file#"$WT_ROOT"/}"
    local rows
    rows=$(awk '
        /^[[:space:]]*#/ { if (!in_block) { first=$0; in_block=1 } next }
        /^[a-zA-Z_][a-zA-Z0-9_]*\(\)[[:space:]]*\{/ {
            name=$0; sub(/\(\).*/, "", name)
            if (in_block && name !~ /^_/ && name !~ /^show_/) {
                p=first; sub(/^[[:space:]]*#[[:space:]]?/, "", p); print name "\t" p
            }
            in_block=0; next
        }
        { in_block=0 }
    ' "$file")
    [[ -z "$rows" ]] && return 0
    printf '### `%s`\n\n| Function | Purpose |\n|---|---|\n' "$rel"
    while IFS=$'\t' read -r name purpose; do
        printf '| `%s` | %s |\n' "$name" "$purpose"
    done <<< "$rows"
    printf '\n'
}

generate() {
    printf '<!-- Generated by scripts/gen-docs.sh from the source doc-comments. Do not edit by hand. -->\n'
    printf '# wt — Command & Function Index\n\n'
    printf 'A generated index of every `wt` command and every public function, with a one-line\n'
    printf 'purpose each. Regenerate with `scripts/gen-docs.sh --write`; CI fails on drift.\n\n'
    emit_commands
    printf '## Functions by file\n\n'
    printf '### Entry\n\n'
    emit_file_section "$WT_ROOT/wt.sh"
    printf '### Commands (`commands/`)\n\n'
    for f in "$WT_ROOT"/commands/*.sh; do emit_file_section "$f"; done
    printf '### Library (`lib/`)\n\n'
    for f in "$WT_ROOT"/lib/*.sh; do emit_file_section "$f"; done
}

case "${1:-}" in
    --write) generate > "$OUT_FILE"; echo "wrote $OUT_FILE" ;;
    --check)
        if ! diff -u "$OUT_FILE" <(generate) >/dev/null 2>&1; then
            echo "COMMANDS.md is stale — run: scripts/gen-docs.sh --write" >&2
            diff -u "$OUT_FILE" <(generate) >&2 || true
            exit 1
        fi
        echo "COMMANDS.md is up to date"
        ;;
    *) generate ;;
esac
